import { describe, expect, it } from "vitest"
import { existsSync, readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, resolve } from "node:path"

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../..")
const read = (name: string) => readFileSync(resolve(repoRoot, name), "utf8")

const ZH = read("README.md")
const EN = read("README_EN.md")

/** The QR image both editions point at. */
const QR = "src/renderer/assets/alipay-qr.png"

describe("release sync", () => {
	const pkg = JSON.parse(read("package.json")) as { version: string }
	const site = read("docs/index.html")

	it("keeps the download site on the version package.json builds", () => {
		const labels = [...site.matchAll(/class="js-version-tag">v([^<]+)</g)].map(
			(m) => m[1],
		)
		expect(labels.length).toBe(3) // hero, nav and downloads section
		for (const label of labels) expect(label).toBe(pkg.version)
	})

	it("points every download button at that version's artifacts", () => {
		// v<version>/my-agent-<version>-<suffix>: the version appears twice, so
		// a half-applied bump (tag directory only) would 404.
		const links = [
			...site.matchAll(/releases\/download\/v([^/"]+)\/my-agent-([\d.]+)-/g),
		]
		expect(links.length).toBe(8)
		for (const [, tag, version] of links) {
			expect(tag).toBe(pkg.version)
			expect(version).toBe(pkg.version)
		}
	})

	it("only offers files the README matrix also lists", () => {
		// Both are generated by the same script, so a name that exists on one
		// side only is a dead link. A subset is fine — the site has no Linux
		// `.zip` button — but never a name the README does not know. The
		// version ends at the first dash, hence the lazy suffix up to a known
		// package extension ("…-mac-arm64.dmg" is one name).
		const files = (md: string) =>
			[
				...new Set(
					[
						...md.matchAll(
							/my-agent-\d[\d.]*-[\w.-]*?\.(?:dmg|zip|exe|AppImage|deb)/g,
						),
					].map((m) => m[0]),
				),
			].sort()
		const siteFiles = files(site)
		expect(siteFiles.length).toBe(8)
		for (const file of siteFiles) expect(files(ZH)).toContain(file)
	})
})

describe("README language switch", () => {
	it("links the two editions to each other", () => {
		expect(ZH).toContain("[English](README_EN.md)")
		expect(EN).toContain("[简体中文](README.md)")
	})

	it("announces the switch above the fold, not at the bottom", () => {
		// A switcher buried under a 900-line document is the same as none. Each
		// edition links to the *other* one, so the needles differ.
		const near = (md: string, needle: string) => {
			const at = md.indexOf(needle)
			return at > -1 && at < 600
		}
		expect(near(ZH, "README_EN.md")).toBe(true)
		expect(near(EN, "简体中文")).toBe(true)
	})

	it("keeps the English edition a mirror, not a summary", () => {
		const count = (md: string) => md.split("```").length
		// Same number of code fences (and therefore code blocks) in both.
		expect(count(EN)).toBe(count(ZH))
		// Same heading count, so no section was folded away in translation.
		const headings = (md: string) =>
			md.split("\n").filter((line) => line.startsWith("#")).length
		expect(headings(EN)).toBe(headings(ZH))
	})
})

describe("README tip jar", () => {
	it("keeps both editions inside the marker pair", () => {
		for (const md of [ZH, EN]) {
			expect(md).toContain("<!-- TIP_JAR_START")
			expect(md).toContain("<!-- TIP_JAR_END -->")
			const start = md.indexOf("<!-- TIP_JAR_START")
			const end = md.indexOf("<!-- TIP_JAR_END -->")
			expect(start).toBeLessThan(end)
		}
	})

	it("shows the payment QR that the app also ships", () => {
		for (const md of [ZH, EN]) {
			expect(md).toContain(`<img src="${QR}"`)
		}
		// A broken path is invisible until someone opens the README on GitHub.
		expect(existsSync(resolve(repoRoot, QR))).toBe(true)
	})

	it("asks for the tip in the project's own voice", () => {
		expect(ZH).toContain("如果你觉得项目对你有帮助，打赏猫球吧")
		expect(EN.toLowerCase()).toContain("treat the cat")
	})
})
